#!/usr/bin/env python
"""Split navtest's log list into N shard scene-filters for parallel scoring.

run_pdm_score_cot evaluates set(scene_loader.tokens) & set(metric_cache.tokens),
so restricting the scene filter to a subset of logs partitions the work exactly.
The metric cache and the preprocessed JSON are built ONCE over all of navtest and
shared by every shard -- only the GPU-bound scoring is sharded.

PDMS is a per-token mean, so concatenating the shard CSVs and averaging over all
rows reproduces the unsharded number.
"""
import argparse, pathlib, yaml


class _QuotedDumper(yaml.SafeDumper):
    """Single-quote string *values*, as upstream navtest.yaml does.

    Ids like ``3309408516525e17`` are plain strings to PyYAML's 1.1 resolver but
    *floats* to OmegaConf's, which overflows them to ``inf``. An unquoted id read
    back through hydra therefore stops matching anything, silently. Keys are
    never ambiguous, so they stay bare and the file stays readable.
    """

    def represent_mapping(self, tag, mapping, flow_style=None):
        node = super().represent_mapping(tag, mapping, flow_style)
        for key_node, _ in node.value:
            key_node.style = None
        return node


_QuotedDumper.add_representer(
    str, lambda d, v: d.represent_scalar("tag:yaml.org,2002:str", v, style="'")
)

ROOT = pathlib.Path("/mnt/efs/users/rod/repos/AutoVLA")
SF = ROOT / "navsim/navsim/planning/script/config/common/train_test_split/scene_filter"
TS = ROOT / "navsim/navsim/planning/script/config/common/train_test_split"

def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("-n", "--shards", type=int, required=True)
    args = ap.parse_args()

    base = yaml.safe_load((SF / "navtest.yaml").read_text())
    logs = base["log_names"]
    # round-robin so each shard sees a similar mix of scene types
    groups = [logs[i :: args.shards] for i in range(args.shards)]

    for i, group in enumerate(groups):
        d = dict(base)
        d["log_names"] = group
        # Keep the inherited token whitelist: navtest is a *subsample* of the
        # stride-1 windows, so log_names alone would yield ~5x the scenes.
        name = f"navtest_shard{i}"
        (SF / f"{name}.yaml").write_text(
            f"# navtest shard {i}/{args.shards}: {len(group)} of {len(logs)} logs.\n"
            f"# Generated by scripts/make_navtest_shards.py -- do not hand-edit.\n"
            + yaml.dump(d, Dumper=_QuotedDumper, sort_keys=False, default_flow_style=False)
        )
        (TS / f"{name}.yaml").write_text(
            f"defaults:\n  - scene_filter: {name}\n\ndata_split: test\n"
        )
        print(f"  {name}: {len(group)} logs")
    print(f"total {len(logs)} logs over {args.shards} shards")
    return 0

if __name__ == "__main__":
    raise SystemExit(main())
